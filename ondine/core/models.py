# Sentinel written into an output cell when a row is skipped under the SKIP
# error policy. It is a failure marker, NOT valid output — quality checks and
# the whole-run guard both treat a cell equal to this as a non-result. Defined
# here (core) so the LLM stage and the quality validator share one spelling.
SKIPPED_OUTPUT_MARKER = "[SKIPPED]"

# Longest provider message quoted in a one-line error summary. Providers
# return whole JSON bodies; past this the line stops being readable.
_MAX_REASON_CHARS = 300


def _shorten(reason: str) -> str:
    """Collapse a provider message to one bounded line."""
    one_line = " ".join(reason.split())
    if len(one_line) <= _MAX_REASON_CHARS:
        return one_line
    return one_line[: _MAX_REASON_CHARS - 1] + "…"


@dataclass
class LLMResponse:
    """Response from a single LLM invocation."""

    text: str
    tokens_in: int
    tokens_out: int
    model: str
    cost: Decimal
    latency_ms: float
    metadata: dict[str, Any] = field(default_factory=dict)
    structured_result: Any = None  # Optional: Pydantic object for structured output (avoids serialize/parse cycle)


@dataclass
class CostEstimate:
    """
    Cost estimation for pipeline execution.

    Provides detailed cost breakdown with Decimal precision to avoid floating-point errors.

    Attributes:
        total_cost: Total cost in USD (Decimal for precision)
        total_tokens: Total tokens consumed (input + output)
        input_tokens: Input tokens sent to LLM
        output_tokens: Output tokens generated by LLM
        rows: Number of rows processed
        breakdown_by_stage: Cost breakdown by pipeline stage
        confidence: Confidence level (estimate, sample-based, actual)

    Example:
        ```python
        result = pipeline.execute()

        # Access costs
        print(f"Total: ${result.costs.total_cost}")
        print(f"Input tokens: {result.costs.input_tokens:,}")
        print(f"Output tokens: {result.costs.output_tokens:,}")
        print(f"Cost per row: ${result.costs.total_cost / result.costs.rows:.4f}")
        ```
    """

    total_cost: Decimal
    total_tokens: int
    input_tokens: int = 0
    output_tokens: int = 0
    rows: int = 0
    breakdown_by_stage: dict[str, Decimal] = field(default_factory=dict)
    confidence: str = "estimate"  # estimate, sample-based, actual


